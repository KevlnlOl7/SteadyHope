/* USER CODE BEGIN 0 */
void Sensor_Init(void)
{
    BNO_Status_t Status = {0};
    BNO055_Init_t BNO055_InitStruct = {0};
    Calib_status_t Calibration = {0};

    uint32_t calibrationStartTime;

    printf("\r\n================================\r\n");
    printf("BNO055 initialization start\r\n");
    printf("================================\r\n");

    ResetBNO055();

    BNO055_InitStruct.ACC_Range = Range_16G;

    BNO055_InitStruct.Axis =
        DEFAULT_AXIS_REMAP;

    BNO055_InitStruct.Axis_sign =
        DEFAULT_AXIS_SIGN;

    BNO055_InitStruct.Clock_Source =
        CLOCK_EXTERNAL;

    BNO055_InitStruct.Mode =
        BNO055_NORMAL_MODE;

    BNO055_InitStruct.OP_Modes =
    		GYRO_ONLY;

    BNO055_InitStruct.Unit_Sel =
        UNIT_ORI_ANDROID |
        UNIT_TEMP_CELCIUS |
        UNIT_EUL_DEG |
        UNIT_GYRO_DPS |
        UNIT_ACC_MS2;

    BNO055_Init(BNO055_InitStruct);

    HAL_Delay(100);

    printf("Gyroscope calibration start\r\n");
    printf("Keep BNO055 stationary\r\n");

    calibrationStartTime = HAL_GetTick();

    do
    {
        getCalibration(&Calibration);

        printf(
            "Gyro calibration: %u/3\r\n",
            Calibration.Gyro
        );

        if (Calibration.Gyro == 3)
        {
            break;
        }

        HAL_Delay(500);

    } while (
        (HAL_GetTick() - calibrationStartTime) < 10000U
    );

    if (Calibration.Gyro == 3)
    {
        printf("Gyroscope calibration completed\r\n");
    }
    else
    {
        printf(
            "Gyroscope calibration timeout, "
            "continue without full calibration\r\n"
        );
    }
    Check_Status(&Status);

    printf(
        "Current operation mode: 0x%02X\r\n",
        (unsigned int)getCurrentMode()
    );

    printf(
        "Self-test result: 0x%02X\r\n",
        Status.STresult
    );

    printf(
        "System status: %u\r\n",
        Status.SYSStatus
    );

    printf(
        "System error: %u\r\n",
        Status.SYSError
    );

    printf("BNO055 initialization finished\r\n");
}

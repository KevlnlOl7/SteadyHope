/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */
/* USER CODE BEGIN Boot_Mode_Sequence_0 */
  int32_t timeout;
/* USER CODE END Boot_Mode_Sequence_0 */

/* USER CODE BEGIN Boot_Mode_Sequence_1 */
  /* Wait until CPU2 boots and enters in stop mode or timeout*/
  timeout = 0xFFFF;
  while((__HAL_RCC_GET_FLAG(RCC_FLAG_D2CKRDY) != RESET) && (timeout-- > 0));
  if ( timeout < 0 )
  {
  Error_Handler();
  }
/* USER CODE END Boot_Mode_Sequence_1 */
  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();
/* USER CODE BEGIN Boot_Mode_Sequence_2 */
/* When system initialization is finished, Cortex-M7 will release Cortex-M4 by means of
HSEM notification */
/*HW semaphore Clock enable*/
__HAL_RCC_HSEM_CLK_ENABLE();
/*Take HSEM */
HAL_HSEM_FastTake(HSEM_ID_0);
/*Release HSEM in order to notify the CPU2(CM4)*/
HAL_HSEM_Release(HSEM_ID_0,0);
/* wait until CPU2 wakes up from stop mode */
timeout = 0xFFFF;
while((__HAL_RCC_GET_FLAG(RCC_FLAG_D2CKRDY) == RESET) && (timeout-- > 0));
if ( timeout < 0 )
{
Error_Handler();
}
/* USER CODE END Boot_Mode_Sequence_2 */

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_USART3_UART_Init();
  MX_BDMA_Init();
  MX_I2C4_Init();
  MX_USART1_UART_Init();
  /* USER CODE BEGIN 2 */
  Sensor_Init();
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */

  while (1)
  {
    /* USER CODE END WHILE */
	  /*
	       * 讀取 BNO055 Gyro
	       */
	      ReadData(&BNO055, SENSOR_GYRO);

	      /*
	       * 改成 milli-DPS 整數格式。
	       * 不需要啟用 printf 浮點數支援。
	       *
	       * 例如：
	       * 1.250 DPS 會傳送成 1250
	       */
	      int32_t gxMilliDps =
	          (int32_t)(BNO055.Gyro.X * 1000.0f);

	      int32_t gyMilliDps =
	          (int32_t)(BNO055.Gyro.Y * 1000.0f);

	      int32_t gzMilliDps =
	          (int32_t)(BNO055.Gyro.Z * 1000.0f);

	      int length = snprintf(
	          imuTxBuffer,
	          sizeof(imuTxBuffer),
	          "GYRO,%ld,%ld,%ld\r\n",
	          (long)gxMilliDps,
	          (long)gyMilliDps,
	          (long)gzMilliDps
	      );

	      if (
	          length > 0 &&
	          length < (int)sizeof(imuTxBuffer)
	      )
	      {
	          /*
	           * USART1 PB6 傳送到 ESP32
	           */
	          imuUartStatus = HAL_UART_Transmit(
	              &huart1,
	              (uint8_t *)imuTxBuffer,
	              (uint16_t)length,
	              100
	          );
	      }

	      imuSampleCount++;

	      printf(
	          "Gyro milli-DPS: %ld, %ld, %ld\r\n",
	          (long)gxMilliDps,
	          (long)gyMilliDps,
	          (long)gzMilliDps
	      );

	      HAL_Delay(100);
    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

